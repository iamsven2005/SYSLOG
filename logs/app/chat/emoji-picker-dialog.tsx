// Recently used emojis (will be stored in localStorage)
const RECENT_EMOJIS_KEY = "recent-emojis"
const MAX_RECENT_EMOJIS = 30

export function EmojiPickerDialog({ open, onOpenChange, onEmojiSelect }: EmojiPickerDialogProps) {
  const [searchQuery, setSearchQuery] = React.useState("")
  const [activeTab, setActiveTab] = React.useState("recent")
  const [recentEmojis, setRecentEmojis] = React.useState<string[]>([])

  // Load recent emojis from localStorage on mount
  React.useEffect(() => {
    if (typeof window !== "undefined") {
      try {
        const stored = localStorage.getItem(RECENT_EMOJIS_KEY)
        if (stored) {
          setRecentEmojis(JSON.parse(stored))
        }
      } catch (error) {
        console.error("Failed to load recent emojis:", error)
      }
    }
  }, [])

  // Save recent emojis to localStorage
  const saveRecentEmoji = (emoji: string) => {
    const updated = [emoji, ...recentEmojis.filter((e) => e !== emoji)].slice(0, MAX_RECENT_EMOJIS)
    setRecentEmojis(updated)

    if (typeof window !== "undefined") {
      try {
        localStorage.setItem(RECENT_EMOJIS_KEY, JSON.stringify(updated))
      } catch (error) {
        console.error("Failed to save recent emojis:", error)
      }
    }
  }

  const handleEmojiClick = (emoji: string) => {
    saveRecentEmoji(emoji)
    onEmojiSelect(emoji)
  }

  // Filter emojis based on search query
  const filteredEmojis = React.useMemo(() => {
    if (!searchQuery.trim()) return []

    const query = searchQuery.toLowerCase()
    const results: string[] = []

    emojiCategories.forEach((category) => {
      category.emojis.forEach((emoji) => {
        if (results.length < 100 && !results.includes(emoji)) {
          results.push(emoji)
        }
      })
    })

    return results
  }, [searchQuery])

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-[500px]">
        <DialogHeader>
          <DialogTitle>Emoji Picker</DialogTitle>
        </DialogHeader>

        <div className="relative mb-4">
          <Search className="absolute left-2 top-2.5 h-4 w-4 text-muted-foreground" />
          <Input
            placeholder="Search emojis..."
            className="pl-8"
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
          />
        </div>

        {searchQuery ? (
          <div className="h-[300px] overflow-y-auto">
            <div className="grid grid-cols-8 gap-2">
              {filteredEmojis.length > 0 ? (
                filteredEmojis.map((emoji) => (
                  <Button
                    key={emoji}
                    variant="ghost"
                    className="h-9 w-9 p-0 hover:bg-accent"
                    onClick={() => handleEmojiClick(emoji)}
                  >
                    <span className="text-xl">{emoji}</span>
                  </Button>
                ))
              ) : (
                <div className="col-span-8 py-8 text-center text-muted-foreground">No emojis found</div>
              )}
            </div>
          </div>
        ) : (
          <Tabs defaultValue="recent" value={activeTab} onValueChange={setActiveTab}>
            <TabsList className="grid grid-cols-9">
              <TabsTrigger value="recent" className="px-2">
                <span className="text-lg" title="Recently Used">
                  🕒
                </span>
              </TabsTrigger>
              {emojiCategories.map((category) => (
                <TabsTrigger key={category.name} value={category.name} className="px-2">
                  <span className="text-lg" title={category.label}>
                    {category.icon}
                  </span>
                </TabsTrigger>
              ))}
            </TabsList>

            <TabsContent value="recent" className="mt-2">
              <ScrollArea className="h-[300px]">
                <div className="grid grid-cols-8 gap-2">
                  {recentEmojis.length > 0 ? (
                    recentEmojis.map((emoji) => (
                      <Button
                        key={emoji}
                        variant="ghost"
                        className="h-9 w-9 p-0 hover:bg-accent"
                        onClick={() => handleEmojiClick(emoji)}
                      >
                        <span className="text-xl">{emoji}</span>
                      </Button>
                    ))
                  ) : (
                    <div className="col-span-8 py-8 text-center text-muted-foreground">No recently used emojis</div>
                  )}
                </div>
              </ScrollArea>
            </TabsContent>

            {emojiCategories.map((category) => (
              <TabsContent key={category.name} value={category.name} className="mt-2">
                <ScrollArea className="h-[300px]">
                  <div className="grid grid-cols-8 gap-2">
                    {category.emojis.map((emoji) => (
                      <Button
                        key={emoji}
                        variant="ghost"
                        className="h-9 w-9 p-0 hover:bg-accent"
                        onClick={() => handleEmojiClick(emoji)}
                      >
                        <span className="text-xl">{emoji}</span>
                      </Button>
                    ))}
                  </div>
                </ScrollArea>
              </TabsContent>
            ))}
          </Tabs>
        )}
      </DialogContent>
    </Dialog>
  )
}
